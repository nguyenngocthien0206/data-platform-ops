"""The company's legacy Postgres: where its operational data lives today (2.0).

The rows are still generated by ``raw_data`` in DuckDB, with the same seeded
hashes, into a scratch database (``paths.generator``); children are generated
from their parents in that scratch copy. Every load and every in-place change
is then written to Postgres, the company's operational database, with one
difference in shape: the generator's ``_loaded_at`` (when the row was written)
is the operational table's ``updated_at``. That column is what the incremental
ingestion into ClickHouse follows.

Rows reach Postgres through CSV and ``COPY``: DuckDB writes an empty string as
``""`` and NULL as nothing, which is exactly how Postgres reads them back, so a
NULL never turns into an empty string or the reverse. Loads are upserts on the
primary key, so a changed row replaces its old version, as an application
writing to its own database would.
"""

from __future__ import annotations

import re
import tempfile
from dataclasses import dataclass, field
from datetime import datetime
from pathlib import Path
from typing import Any

import duckdb
from psycopg import sql

from platform_ops.common.config import Settings
from platform_ops.common.db import RAW_SCHEMA
from platform_ops.common.servers import connect_postgres
from platform_ops.simulation import raw_data
from platform_ops.simulation.legacy_reports import create_reports

LOADED_AT = "_loaded_at"
UPDATED_AT = "updated_at"

_TYPES = {
    "BIGINT": "bigint",
    "INTEGER": "integer",
    "VARCHAR": "text",
    "TIMESTAMP": "timestamp",
    "DATE": "date",
    "BOOLEAN": "boolean",
}


def postgres_type(duckdb_type: str) -> str:
    decimal = re.fullmatch(r"DECIMAL\((\d+),\s*(\d+)\)", duckdb_type)
    if decimal:
        return f"numeric({decimal[1]}, {decimal[2]})"
    return _TYPES[duckdb_type]


def operational_columns(table: str) -> list[tuple[str, str]]:
    """(name, Postgres type) of the operational table: the generator's, with updated_at."""
    return [
        (UPDATED_AT if name == LOADED_AT else name, postgres_type(data_type))
        for name, data_type in raw_data._ddl_columns(table)
    ]


@dataclass
class LegacyCompany:
    """The scratch generator and the Postgres it writes to."""

    settings: Settings
    plan: raw_data.RawDataPlan = field(init=False)
    generator: duckdb.DuckDBPyConnection = field(init=False)

    def __post_init__(self) -> None:
        self.plan = raw_data.RawDataPlan.from_settings(self.settings)
        self.generator = self._fresh_generator()

    @property
    def schema(self) -> str:
        return self.settings.company.name(self.settings.company.legacy_schema)

    def _fresh_generator(self) -> duckdb.DuckDBPyConnection:
        path = self.settings.resolve(self.settings.paths.generator)
        path.parent.mkdir(parents=True, exist_ok=True)
        for leftover in (path, path.with_suffix(path.suffix + ".wal")):
            leftover.unlink(missing_ok=True)
        connection = duckdb.connect(str(path))
        connection.execute(f"CREATE SCHEMA IF NOT EXISTS {RAW_SCHEMA}")
        return connection

    def close(self) -> None:
        self.generator.close()

    # -- the company's history up to the window start -----------------------------

    def seed(self) -> dict[str, int]:
        """Recreate the operational schema and load everything up to the window start."""
        counts = raw_data.seed(self.generator, self.settings)
        with connect_postgres(self.settings) as connection:
            schema = sql.Identifier(self.schema)
            connection.execute(sql.SQL("DROP SCHEMA IF EXISTS {} CASCADE").format(schema))
            connection.execute(sql.SQL("CREATE SCHEMA {}").format(schema))
            for table in raw_data.TABLES:
                columns = sql.SQL(", ").join(
                    sql.SQL("{} {}").format(sql.Identifier(name), sql.SQL(data_type))
                    for name, data_type in operational_columns(table)
                )
                key = sql.Identifier(raw_data.PRIMARY_KEYS[table])
                connection.execute(
                    sql.SQL("CREATE TABLE {}.{} ({}, PRIMARY KEY ({}))").format(
                        schema, sql.Identifier(table), columns, key
                    )
                )
                target = sql.SQL("{}.{}").format(schema, sql.Identifier(table))
                self._copy(connection, table, f"SELECT * FROM {RAW_SCHEMA}.{table}", target)
            connection.commit()
        create_reports(self.settings)
        return counts

    # -- one simulated day ----------------------------------------------------------

    def arrive(
        self,
        day_index: int,
        after: datetime,
        until: datetime,
        changes_at: datetime,
        price_changes: int,
        profile_changes: int,
    ) -> tuple[dict[str, int], dict[str, int]]:
        """New rows in ``(after, until]`` and the day's in-place changes, into Postgres."""
        loaded = raw_data.load_window(self.generator, self.plan, after=after, until=until)
        changed = raw_data.apply_daily_changes(
            self.generator,
            self.plan,
            day_index,
            at=changes_at,
            price_changes=price_changes,
            profile_changes=profile_changes,
        )
        window = (
            f"{LOADED_AT} > TIMESTAMP '{after:%Y-%m-%d %H:%M:%S}' "
            f"AND {LOADED_AT} <= TIMESTAMP '{until:%Y-%m-%d %H:%M:%S}'"
        )
        with connect_postgres(self.settings) as connection:
            for table in raw_data.TABLES:
                self._upsert(connection, table, window)
            connection.commit()
        return loaded, changed

    # -- moving rows ---------------------------------------------------------------

    def _copy(self, connection: Any, table: str, select: str, target: sql.Composable) -> int:
        """COPY the rows ``select`` returns, in primary-key order, into ``target`` (qualified)."""
        key = raw_data.PRIMARY_KEYS[table]
        names = [name for name, _ in raw_data._ddl_columns(table)]
        with tempfile.TemporaryDirectory() as folder:
            path = Path(folder) / f"{table}.csv"
            self.generator.execute(
                f"COPY ({select} ORDER BY {key}) TO '{path.as_posix()}' (FORMAT csv, HEADER false)"
            )
            columns = sql.SQL(", ").join(
                sql.Identifier(UPDATED_AT if n == LOADED_AT else n) for n in names
            )
            statement = sql.SQL("COPY {} ({}) FROM STDIN (FORMAT csv)").format(target, columns)
            rows = 0
            with connection.cursor().copy(statement) as copy, path.open("rb") as source:
                while chunk := source.read(1 << 20):
                    copy.write(chunk)
                    rows += chunk.count(b"\n")
        return rows

    def _upsert(self, connection: Any, table: str, window: str) -> int:
        """Insert new rows and replace changed ones, from the generator's window."""
        staged = sql.Identifier(f"incoming_{table}")
        target = sql.SQL("{}.{}").format(sql.Identifier(self.schema), sql.Identifier(table))
        connection.execute(
            sql.SQL("CREATE TEMP TABLE {} (LIKE {}) ON COMMIT DROP").format(staged, target)
        )
        rows = self._copy(
            connection, table, f"SELECT * FROM {RAW_SCHEMA}.{table} WHERE {window}", staged
        )
        if rows == 0:
            return 0
        key = raw_data.PRIMARY_KEYS[table]
        names = [name for name, _ in operational_columns(table)]
        updates = sql.SQL(", ").join(
            sql.SQL("{0} = EXCLUDED.{0}").format(sql.Identifier(n)) for n in names if n != key
        )
        connection.execute(
            sql.SQL(
                "INSERT INTO {} SELECT * FROM {} ORDER BY {} ON CONFLICT ({}) DO UPDATE SET {}"
            ).format(target, staged, sql.Identifier(key), sql.Identifier(key), updates)
        )
        return rows
