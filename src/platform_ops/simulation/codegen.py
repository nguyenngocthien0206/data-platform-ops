"""Generate the repetitive mart rollups from a declarative spec.

Each team has a handful of hand-written core facts with real business logic.
Dashboards then want the same numbers cut by day, week and month, and by one
dimension or another. Those cuts are mechanical, so they are generated here, and
the output is committed because dbt reads models from disk.

Change the spec below and rerun::

    uv run python -m platform_ops.simulation.codegen

A test regenerates into memory and compares with the committed files, so a hand
edit to a generated model fails CI rather than drifting from the spec.
"""

