def _render_model(family: RollupFamily, grain: str, dimension: str) -> str:
    measures = ",\n".join(f"    {expr} as {alias}" for alias, expr in family.measures)
    return (
        f"{HEADER}"
        f"select\n"
        f"    cast(date_trunc('{GRAIN_TRUNC[grain]}', {family.time_column}) as date)"
        f" as period_start,\n"
        f"    {dimension},\n"
        f"{measures}\n"
        f"from {{{{ ref('{family.source}') }}}}\n"
        f"group by 1, 2\n"
    )


def _render_schema(team: str, names: list[str], dimensions: dict[str, str]) -> str:
    lines = [
        "# GENERATED by platform_ops.simulation.codegen. Do not edit by hand.",
        "version: 2",
        "",
        "models:",
    ]
    for name in names:
        lines += [
            f"  - name: {name}",
            "    data_tests:",
            "      - unique_combination_of_columns:",
            "          arguments:",
            f"            combination_of_columns: [period_start, {dimensions[name]}]",
        ]
    return "\n".join(lines) + "\n"


def render_all() -> dict[str, str]:
    """Every generated file, keyed by its path relative to the dbt project."""
    files: dict[str, str] = {}
    per_team: dict[str, list[str]] = {}
    dimension_of: dict[str, str] = {}
    for family in ROLLUPS:
        for grain in family.grains:
            for dimension in family.dimensions:
                name = family.model_name(grain, dimension)
                if name in dimension_of:
                    raise ValueError(f"duplicate generated model name: {name}")
                path = f"models/marts/{family.team}/generated/{name}.sql"
                files[path] = _render_model(family, grain, dimension)
                per_team.setdefault(family.team, []).append(name)
                dimension_of[name] = dimension
    for team, names in per_team.items():
        path = f"models/marts/{team}/generated/_generated.yml"
        files[path] = _render_schema(team, sorted(names), dimension_of)
    return files


def generated_dirs(dbt_root: Path) -> list[Path]:
    teams = sorted({family.team for family in ROLLUPS})
    return [dbt_root / "models" / "marts" / team / "generated" for team in teams]


def write_all(dbt_root: Path) -> list[Path]:
    """Write every generated file and remove stale ones. Returns what was written."""
    files = render_all()
    wanted = {dbt_root / relative for relative in files}
    for directory in generated_dirs(dbt_root):
        if directory.exists():
            for existing in directory.iterdir():
                if existing.is_file() and existing not in wanted:
                    existing.unlink()
    written: list[Path] = []
    for relative, content in sorted(files.items()):
        target = dbt_root / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content, encoding="utf-8", newline="\n")
        written.append(target)
    return written


def main() -> None:
    dbt_root = Path(__file__).resolve().parents[3] / "dbt"
    written = write_all(dbt_root)
    models = sum(1 for path in written if path.suffix == ".sql")
    print(f"wrote {models} generated models under {dbt_root}")


if __name__ == "__main__":
    main()
